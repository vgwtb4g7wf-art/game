def guard_for(country,seed):return Random(str(seed)).choice(GUARDS[country])

def intent(profile,round_number):
    if profile.get('heal',0) and round_number%3==0:return 'heal',profile['heal']
    period=profile.get('guard_every',3 if profile['defensive'] else 0)
    if period and round_number%period==0:return 'guard',profile['block']
    damage=profile['attack']+(profile.get('opening',0) if round_number==1 else 0)
    if round_number%3==0:damage+=profile.get('heavy',0)
    if round_number>=4:damage+=profile.get('ramp',0)
    return 'attack',damage


def profile_for(name,tier):
    record=BESTIARY[name]
    if record['tier']!=tier:raise ValueError('Сложность противника не соответствует каталогу.')
    traits=ARCHETYPES[record['kind']]
    # На первой ступени убираем усиленный старт: новый герой должен переживать несколько ходов.
    profile=dict(hp=max(6,(12,24,30,36,50)[tier-1]+traits['hp']),attack=(4,5,6,7,9)[tier-1],
        armor=(0,0,2,3,4)[tier-1]+(min(1,traits['armor']) if tier==1 else traits['armor']),
        escape=(2,3,4,6,8)[tier-1],block=1+tier//2,defensive=bool(traits['guard_every']),
        fame_loss=tier+1,guard_every=traits['guard_every'],heal=traits['heal'],heavy=traits['heavy'] if tier>1 else 0,
        opening=traits['opening'] if tier>1 else 0,ramp=traits['ramp'] if tier>1 else 0)

    if record['guard']:
        countries=list(GUARD_NAMES);i=countries.index(record['country']);j=GUARDS[record['country']].index(name)
        profile['hp']+=i%3-1
        profile['armor']+=j
        if i==0:profile['armor']+=2;profile['hp']-=2
        elif i==1:profile['opening']+=1
        elif i==2:
            if profile['heal']:profile['heal']+=1
            else:profile['block']+=2
        elif i==3:profile['ramp']+=1
        elif i==4:profile['hp']+=3;profile['armor']=max(0,profile['armor']-1)
        elif i==5:profile['heavy']+=1
        elif i==6:profile['attack']+=1;profile['hp']-=3
        else:profile['heavy']+=1;profile['heal']=1
        if j==0:profile['opening']+=i%2
        else:profile['block']+=1+i//4
    return profile

