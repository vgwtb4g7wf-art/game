def register(name,tier,country,kind,index,guard=False):
    if name in BESTIARY:raise ValueError(f'Повтор имени: {name}')
    BESTIARY[name]=dict(name=name,tier=tier,country=country,kind=kind,guard=guard,
        description=ARCHETYPES[kind]['description'])
    if tier==1 and kind in ('охотник','преследователь'):
        BESTIARY[name]['description']='Обычные атаки; усиление у этого молодого существа ещё не развито.'
