"""Небольшие деревья: два общих узла, затем один из двух путей."""
from eterion import BRANCHES

COSTS = (40, 70, 110, 160)
TREES = {
 'Мощь': {'common': ['Закалка','Владение оружием'], 'left': ['Несокрушимость','Крепость'], 'right': ['Натиск','Сокрушение']},
 'Знания': {'common': ['Грамотность','Тайные науки'], 'left': ['Мудрость','Хранитель знаний'], 'right': ['Чародейство','Архимаг']},
 'Хитрость': {'common': ['Наблюдательность','Скрытность'], 'left': ['Ловкость рук','Призрачный шаг'], 'right': ['Меткость','Безупречный выстрел']},
 'Дипломатия': {'common': ['Этикет','Красноречие'], 'left': ['Влияние','Миротворец'], 'right': ['Твёрдая воля','Командир']},
}
PATH_NAMES = {'Мощь': ['Защитник','Завоеватель'], 'Знания': ['Хранитель','Чародей'],
              'Хитрость': ['Лазутчик','Стрелок'], 'Дипломатия': ['Посол','Предводитель']}


def unlocked(hero):
    paths = getattr(hero,'paths',{})
    result=[]
    for branch,level in hero.branches.items():
        tree=TREES[branch]
        result.extend(tree['common'][:min(level,2)])
        if level>2:
            result.extend(tree[paths.get(branch) or 'left'][:level-2])
    return result
